"""Read-only lookup for the locally stored Buffalo Sabres 2026-27 schedule.

The data file is generated by tools/build_sabres_schedule.py and lives in the
 configured knowledge folder. Keeping the lookup explicit avoids relying on
 keyword snippets from a large JSON document when the user asks about a date,
 opponent, venue or jersey.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import re
import unicodedata
import zoneinfo
from pathlib import Path

import config

DATA_FILENAME = "Buffalo-Sabres-2026-27-Schedule.json"
ET = zoneinfo.ZoneInfo("America/New_York")

MONTHS = {
    "january": 1, "jan": 1,
    "february": 2, "feb": 2,
    "march": 3, "mar": 3,
    "april": 4, "apr": 4,
    "may": 5,
    "june": 6, "jun": 6,
    "july": 7, "jul": 7,
    "august": 8, "aug": 8,
    "september": 9, "sep": 9, "sept": 9,
    "october": 10, "oct": 10,
    "november": 11, "nov": 11,
    "december": 12, "dec": 12,
}

JERSEY_TERMS = {
    "hometown remix": "Hometown Remix",
    "hometown": "Hometown Remix",
    "remix": "Hometown Remix",
    "goathead": "Black and Red Goathead",
    "black and red": "Black and Red Goathead",
    "black & red": "Black and Red Goathead",
    "black/red": "Black and Red Goathead",
    "royal blue": "Home Royal Blue",
    "home blue": "Home Royal Blue",
    "road white": "Road White",
    "away white": "Road White",
}


def _plain(value: str) -> str:
    text = unicodedata.normalize("NFKD", str(value))
    text = "".join(c for c in text if not unicodedata.combining(c)).casefold()
    return re.sub(r"[^a-z0-9]+", " ", text).strip()


def _data_path(path: str | os.PathLike | None = None) -> Path | None:
    if path:
        candidate = Path(path)
        return candidate if candidate.is_file() else None
    override = os.environ.get("JARVIS_SABRES_SCHEDULE")
    if override and Path(override).is_file():
        return Path(override)
    dirs = config.get("assistant_knowledge_dirs", []) or []
    if not isinstance(dirs, list):
        dirs = [dirs]
    for item in dirs:
        candidate = Path(str(item)).expanduser() / DATA_FILENAME
        if candidate.is_file():
            return candidate
    return None


def load_data(path: str | os.PathLike | None = None) -> dict:
    found = _data_path(path)
    if found is None:
        raise FileNotFoundError(DATA_FILENAME)
    return json.loads(found.read_text(encoding="utf-8-sig"))


def _dates(query: str, today: dt.date) -> set[str]:
    found: set[str] = set()
    for match in re.finditer(r"\b(\d{4})-(\d{1,2})-(\d{1,2})\b", query):
        try:
            found.add(dt.date(int(match[1]), int(match[2]), int(match[3])).isoformat())
        except ValueError:
            pass
    for name, month in MONTHS.items():
        pattern = rf"\b{name}\.?\s+(\d{{1,2}})(?:st|nd|rd|th)?(?:\s+(\d{{4}}))?\b"
        for match in re.finditer(pattern, query):
            year = int(match[2]) if match[2] else (2026 if month >= 10 else 2027)
            try:
                found.add(dt.date(year, month, int(match[1])).isoformat())
            except ValueError:
                pass
    for match in re.finditer(r"\b(\d{1,2})/(\d{1,2})(?:/(\d{2,4}))?\b", query):
        month, day = int(match[1]), int(match[2])
        raw_year = match[3]
        if raw_year:
            year = int(raw_year)
            year += 2000 if year < 100 else 0
        else:
            year = 2026 if month >= 10 else 2027
        try:
            found.add(dt.date(year, month, day).isoformat())
        except ValueError:
            pass
    return found


def _jersey(query: str) -> str | None:
    for term, jersey in JERSEY_TERMS.items():
        if term in query:
            return jersey
    return None


def _opponents(query: str, games: list[dict]) -> set[str]:
    plain = _plain(query)
    words = set(re.findall(r"\b[a-z0-9]{2,}\b", plain))
    candidates = {str(g.get("opponent") or "") for g in games}
    candidates.discard("")
    found: set[str] = set()
    for opponent in candidates:
        tokens = [token for token in _plain(opponent).split() if len(token) >= 3]
        if tokens and any(token in words for token in tokens):
            found.add(opponent)
    abbreviations = {str(g.get("opponent_abbrev") or "") for g in games} - {""}
    for abbrev in abbreviations:
        if abbrev.lower() in words:
            found.update(g["opponent"] for g in games if g.get("opponent_abbrev") == abbrev)
    return found


def _compact(game: dict) -> dict:
    keys = ("date", "day", "start_et", "opponent", "opponent_abbrev", "site",
            "venue", "jersey", "tv", "result", "game_type")
    return {key: game.get(key) for key in keys}


def _sentence(game: dict) -> str:
    """One line with every answer detail the model needs to repeat verbatim."""
    verb = "host" if game.get("site") == "Home" else "visit"
    parts = [
        f"{game['day']}, {game['date']}: Sabres {verb} {game['opponent']} at "
        f"{game['venue']}, {game['start_et']}, wearing {game['jersey']}"
    ]
    tv = [str(channel) for channel in (game.get("tv") or []) if str(channel).strip()]
    if tv:
        parts.append("TV: " + ", ".join(tv))
    if game.get("result"):
        parts.append("Result: " + str(game["result"]))
    return "; ".join(parts) + "."


def lookup(query: str = "", path: str | os.PathLike | None = None,
           now: dt.date | None = None) -> dict:
    """Return games matching a natural-language query about the Sabres schedule."""
    try:
        data = load_data(path)
    except (OSError, ValueError) as exc:
        return {"ok": False, "error": f"Sabres schedule unavailable: {exc}"}

    games = list(data.get("games") or [])
    if not games:
        return {"ok": False, "error": "Sabres schedule is empty"}

    raw = str(query or "")
    lower = raw.casefold()
    today = now or dt.datetime.now(ET).date()

    special = ""
    if "season opener" in lower or "first game" in lower:
        special = "opener"
    elif "home opener" in lower:
        special = "home_opener"
    elif "season finale" in lower or "final game" in lower or "last game" in lower:
        special = "finale"

    all_games = any(word in lower for word in ("all games", "full schedule", "entire schedule",
                                               "every game", "whole season", "list the schedule"))
    preseason = "preseason" in lower or "pre-season" in lower
    if preseason:
        games = [g for g in games if g.get("game_type") == "Preseason"]
    elif all_games:
        pass
    else:
        games = [g for g in games if g.get("game_type") == "Regular Season"]

    if special == "opener":
        games = [g for g in games if g.get("game_type") == "Regular Season"][:1]
    elif special == "home_opener":
        games = [g for g in games if g.get("game_type") == "Regular Season"
                 and g.get("site") == "Home"][:1]
    elif special == "finale":
        games = [g for g in games if g.get("game_type") == "Regular Season"][-1:]

    wanted_dates = _dates(lower, today)
    if "tonight" in lower or "today" in lower:
        wanted_dates.add(today.isoformat())
    elif "tomorrow" in lower:
        wanted_dates.add((today + dt.timedelta(days=1)).isoformat())
    if wanted_dates and not special:
        games = [g for g in games if g.get("date") in wanted_dates]

    opponents = _opponents(lower, games)
    if opponents and not special:
        games = [g for g in games if g.get("opponent") in opponents]

    jersey = _jersey(lower)
    if jersey and not special:
        games = [g for g in games if g.get("jersey") == jersey]

    if "at home" in lower or "home game" in lower:
        games = [g for g in games if g.get("site") == "Home"]
    elif "on the road" in lower or "away game" in lower or "road game" in lower:
        games = [g for g in games if g.get("site") == "Away"]

    next_only = "next game" in lower or "next sabres game" in lower
    if next_only or "upcoming" in lower:
        games = [g for g in games if str(g.get("date") or "") >= today.isoformat()]

    jersey_question = ("jersey" in lower or "uniform" in lower or "sweater" in lower)
    if jersey_question and not (wanted_dates or opponents or jersey or special):
        games = [g for g in games if g.get("jersey") in ("Hometown Remix", "Black and Red Goathead")]
        all_games = True  # All 18 alternate dates fit; no "ask for full schedule" note.

    if not (all_games or wanted_dates or opponents or jersey or special or jersey_question
            or next_only or "upcoming" in lower):
        games = [g for g in games if str(g.get("date") or "") >= today.isoformat()]

    games.sort(key=lambda g: (str(g.get("date") or ""), str(g.get("start_utc") or "")))
    if next_only:
        games = games[:1]
    limited = False
    if not all_games and len(games) > 12:
        limited = True
        games = games[:12]

    if not games:
        return {"ok": True, "count": 0, "games": [],
                "summary": "No Sabres games matched that request."}

    if len(games) == 1:
        summary = _sentence(games[0])
    else:
        first = _sentence(games[0])
        last = _sentence(games[-1])
        summary = f"Found {len(games)} games. First: {first} Last: {last}"
    if limited:
        summary += " Showing the first 12; ask for the full schedule to see every game."

    return {
        "ok": True,
        "count": len(games),
        "truncated": limited,
        "games": [_compact(g) for g in games],
        "summary": summary,
    }
